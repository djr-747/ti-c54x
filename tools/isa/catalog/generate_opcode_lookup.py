#!/usr/bin/env python3
"""Generate the standalone first-word opcode lookup fragment.

Module contract
---------------
Owns: deterministic expansion of immutable :class:`OpcodeRow` records into a
logical 65,536-entry first-word identity lookup and a sparse standard-C
designated-initializer fragment.  The command-line surface owns reading the
catalog, writing the checked-in derivative, and checking for stale output.
Does not own: catalog syntax/normalization, C compilation, opcode semantics,
operand extraction, runtime initialization, or mutable process state.  The
generator retains no caller-owned mutable data and performs no environment
reads.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
from typing import Sequence

if __package__ in (None, ""):
    # Direct execution is a supported CLI mode.  Resolve the repository root
    # from this file, rather than relying on the caller's working directory.
    _REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
    if str(_REPOSITORY_ROOT) not in sys.path:
        sys.path.insert(0, str(_REPOSITORY_ROOT))

from tools.isa.catalog.opcode_catalog_schema import (  # noqa: E402
    OpcodeCatalogError,
    OpcodeRow,
    parse_catalog,
    validate_catalog_rows,
)


UINT16_MAX = (1 << 16) - 1
UINT16_WORD_COUNT = UINT16_MAX + 1


def _build_lookup_validated(rows: tuple[OpcodeRow, ...]) -> tuple[int, ...]:
    """Build a lookup from rows already checked by the shared schema."""

    lookup = [0] * UINT16_WORD_COUNT
    for word in range(UINT16_WORD_COUNT):
        for identity, row in enumerate(rows, 1):
            if (word & row.first_word_mask) == row.first_word_value:
                lookup[word] = identity
                break
    return tuple(lookup)


def build_lookup(rows: Sequence[OpcodeRow]) -> tuple[int, ...]:
    """Build ``word -> opcode identity`` in catalog declaration order.

    Identity zero is reserved for UNKNOWN; the first row receives identity
    one.  Every 16-bit word is considered, including words that remain zero.
    """

    normalized = validate_catalog_rows(rows)
    return _build_lookup_validated(normalized)


def render_lookup(rows: Sequence[OpcodeRow]) -> str:
    """Render a deterministic sparse C initializer fragment for ``rows``."""

    normalized = validate_catalog_rows(rows)
    lookup = _build_lookup_validated(normalized)
    lines = [
        "/*",
        " * Generated by tools/isa/catalog/generate_opcode_lookup.py.",
        " * Source: src/isa/catalog/opcode_catalog.def.",
        " * DO NOT EDIT: regenerate this tracked fragment from the catalog.",
        " */",
    ]
    for word, identity in enumerate(lookup):
        if identity == 0:
            continue
        symbol = normalized[identity - 1].symbol
        lines.append(
            f"[0x{word:04X}] = (uint16_t)TI_C54X_OPCODE_ID_{symbol},"
        )
    return "\n".join(lines) + "\n"


def _default_catalog_path() -> Path:
    return Path(__file__).resolve().parents[3] / "src/isa/catalog/opcode_catalog.def"


def _default_output_path() -> Path:
    return Path(__file__).resolve().parents[3] / "generated/isa/catalog/opcode_first_word.inc"


def _expected_output(catalog_path: Path) -> str:
    return render_lookup(parse_catalog(catalog_path.read_text(encoding="utf-8")))


def _run(args: argparse.Namespace) -> int:
    catalog_path = args.catalog
    output_path = args.output
    try:
        expected = _expected_output(catalog_path)
    except (OSError, UnicodeError, OpcodeCatalogError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        try:
            actual = output_path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            print(f"stale or missing generated lookup: {output_path}", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"stale generated lookup: {output_path}", file=sys.stderr)
            return 1
        return 0

    try:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(expected, encoding="utf-8")
    except (OSError, UnicodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Run generation or a read-only stale-artifact check."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=_default_catalog_path())
    parser.add_argument("--output", type=Path, default=_default_output_path())
    parser.add_argument(
        "--check",
        action="store_true",
        help="check the output without creating or modifying any file",
    )
    return _run(parser.parse_args(argv))


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())


__all__ = [
    "UINT16_MAX",
    "UINT16_WORD_COUNT",
    "build_lookup",
    "main",
    "render_lookup",
]
