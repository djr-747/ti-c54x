/* Module contract
 * Owns: pure two-word STH-by-SHIFT WORD16 memory-write effects over one
 * signed-SHIFT-shifted accumulator high word (bits 31-16 of the
 * accumulator shifted arithmetically by the signed 5-bit second-word
 * SHIFT count, -16 to +15), one direct-DP, MOD0-MOD3 standard-indirect,
 * or MOD4-family indirect
 * address, and one source select. SXM rides hostile and unconsumed:
 * every encoded shift is a pure shift-and-extract over source bits.
 * Does not own: opcode inventory, operand-layout definitions, address
 * resolution, buses, CPU or architectural state, sequencing, timing,
 * observers, diagnostics, allocation, or callbacks.
 */

